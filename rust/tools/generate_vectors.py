"""Public non-production vectors, independent Python cryptography implementation.
Run from any directory. Compares exact v1 framing, HKDF, AEAD, Argon2id v19 p=4.
No user/device secrets are read. Fixed bytes are solely for interoperability tests.
"""
from pathlib import Path
from struct import pack
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives.kdf.argon2 import Argon2id
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

b16=lambda x:pack('>H',len(x))+x
header=lambda t,n:b'RVLT'+pack('>HBI',1,t,n)
target=b'public-test-target';purpose=b'public-test-purpose';generation=1
context=b16(target)+b16(purpose)+pack('>Q',generation)
dek=bytes(range(32));recovery=bytes(range(32,64));plain=b'public test-only plaintext'
salt=bytes(range(64,96));nonce=bytes(range(96,108));route=bytes(range(108,124))
def info(label,kind=None):return b'RVLT/v1/'+label+b'\0'+context+(route+bytes([kind]) if kind else b'')
def derive(ikm,i):return HKDF(algorithm=hashes.SHA256(),length=32,salt=salt,info=i).derive(ikm)
prefix=context+salt+nonce+pack('>I',len(plain)+16)
aad=header(2,len(prefix)+len(plain)+16)+prefix
data=aad+AESGCM(derive(dek,info(b'data'))).encrypt(nonce,plain,aad)
prefix=context+route+b'\x03'+b16(b'')+salt+nonce+pack('>I',48)
aad=header(3,len(prefix)+48)+prefix
wrap=aad+AESGCM(derive(recovery,info(b'recovery',3))).encrypt(nonce,dek,aad)
psalt=bytes(range(16));password=b'public test-only password'
argon=Argon2id(salt=psalt,length=32,iterations=3,lanes=4,memory_cost=65536).derive(password)
prefix=context+route+b'\x01'+b16(psalt)+salt+nonce+pack('>I',48)
aad=header(3,len(prefix)+48)+prefix
password_wrap=aad+AESGCM(derive(argon,info(b'password',1))).encrypt(nonce,dek,aad)
values=dict(password_wrap=password_wrap,data=data,recovery_wrap=wrap,plaintext=plain,dek=dek,recovery=recovery,password=password,password_salt=psalt,argon2id=argon)
p=Path(__file__).resolve().parents[1]/'tests/fixtures/v1.txt'
p.write_text('# PUBLIC NON-PRODUCTION TEST-ONLY VALUES. Generated by tools/generate_vectors.py.\n'+''.join(f'{k}={v.hex()}\n' for k,v in values.items()))
print('Wrote public test vectors; no values printed.')
